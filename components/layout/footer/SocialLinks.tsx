const MagneticSocialLink: React.FC<{ item: SocialLinkItem }> = ({ item }) => {
  const linkRef = useRef<HTMLAnchorElement | null>(null);
  const [pos, setPos] = useState({ x: 0, y: 0 });
  const [prefersReducedMotion, setPrefersReducedMotion] = useState(false);

  useEffect(() => {
    if (typeof window !== 'undefined') {
      setPrefersReducedMotion(
        window.matchMedia('(prefers-reduced-motion: reduce)').matches
      );
    }
  }, []);

  const handleMouseMove = (e: React.MouseEvent<HTMLAnchorElement>) => {
    if (prefersReducedMotion || !linkRef.current) return;
    const rect = linkRef.current.getBoundingClientRect();
    const x = (e.clientX - (rect.left + rect.width / 2)) * 0.3;
    const y = (e.clientY - (rect.top + rect.height / 2)) * 0.3;
    setPos({ x, y });
  };

  const handleMouseLeave = () => {
    setPos({ x: 0, y: 0 });
  };

  return (
    <motion.a
      ref={linkRef}
      href={item.url}
      target="_blank"
      rel="noreferrer"
      aria-label={item.label}
      onMouseMove={handleMouseMove}
      onMouseLeave={handleMouseLeave}
      animate={{ x: pos.x, y: pos.y }}
      transition={{ type: 'spring', stiffness: 240, damping: 18, mass: 0.2 }}
      className="group relative flex items-center justify-center w-10 h-10 rounded-full bg-emerald-900/60 hover:bg-[#3FA85B] text-emerald-200 hover:text-white border border-emerald-700/50 hover:border-[#3FA85B] transition-colors duration-200 focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-[#3FA85B] focus-visible:ring-offset-2 focus-visible:ring-offset-[#0F4C2A]"
    >
      <SocialIcon platform={item.platform} className="w-4 h-4 transition-transform duration-200 group-hover:scale-110" />
    </motion.a>
  );
};

export const SocialLinks: React.FC<{ className?: string }> = ({ className = '' }) => {
  return (
    <div className={`flex items-center gap-2.5 ${className}`}>
      {siteConfig.socials.map((item) => (
        <MagneticSocialLink key={item.platform} item={item} />
      ))}
    </div>
  );
};
